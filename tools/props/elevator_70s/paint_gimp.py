 if role in ('brushed_steel','door_satin','aged_brass'):
  for k in range(170):
   yy=y+rng.randrange(8,248);xx=x+rng.randrange(8,220);d=rng.choice([-8,-5,3,6]);line((xx,yy),(min(x+248,xx+rng.randrange(9,66)),yy),tuple(v+d for v in c),.6)
