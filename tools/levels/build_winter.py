#!/usr/bin/env python3
"""Author the Winter Place with the committed snow kit and ordinary geometry.

No textures, models, weather or movement behavior are generated by this tool.
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path
import random
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'props'))
from string_lights import SPANS, attachment_height, lights

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / 'assets/levels/winter.json'
