/// Tiny deterministic LCG so the stress test uses no external dependency.
struct Lcg(u64);

impl Lcg {
    fn next_u32(&mut self) -> u32 {
        self.0 = self
            .0
            .wrapping_mul(6_364_136_223_846_793_005)
            .wrapping_add(1_442_695_040_888_963_407);
        (self.0 >> 33) as u32
    }

    fn unit(&mut self) -> f32 {
        self.next_u32() as f32 / u32::MAX as f32
    }

    fn range(&mut self, low: f32, high: f32) -> f32 {
        (high - low).mul_add(self.unit(), low)
    }

    fn int(&mut self, low: i32, high: i32) -> i32 {
        let span = u32::try_from(high - low + 1).unwrap_or(1).max(1);
        low + i32::try_from(self.next_u32() % span).unwrap_or(0)
    }
}

#[test]
fn deterministic_fuzz_levels_bake_and_build_within_budget() {
    // 48 pseudo-random but valid levels: overlapping rooms, mixed ceiling
    // heights, fixture grids, openings, props and odd rotations. Fixed seed, so
    // a failure reproduces exactly.
    let catalog = shipped_catalog();
    let mut assets = shipped_assets();
    let models = [
        "core:chair",
        "core:crate",
        "core:plant",
        "core:table",
        "spooner-man",
    ];
    let mut rng = Lcg(0x5eed_1234_abcd_0001);
    for case in 0..48 {
        let room_count = usize::try_from(rng.int(1, 4)).unwrap_or(0);
        let mut rooms = Vec::new();
        for _ in 0..room_count {
            let width = rng.range(2.0, 40.0);
            let depth = rng.range(2.0, 40.0);
            let height = rng.range(2.0, 6.0);
            let x = rng.range(-10.0, 10.0);
            let z = rng.range(-10.0, 10.0);
            rooms.push(room(x, z, width, depth, height));
        }
        let light_count = usize::try_from(rng.int(0, 12)).unwrap_or(0);
        let mut lights = Vec::new();
        for _ in 0..light_count {
            let x = rng.range(-10.0, 30.0);
            let z = rng.range(-10.0, 30.0);
            let intensity = rng.range(0.0, 2.5);
            // Mix authored colours into the fuzz so saturated and zero channels
            // reach every geometry path, not only the greyscale default.
            let entry = match rng.next_u32() % 4 {
                0 => light(x, z, Some(intensity)),
                1 => format!(
                    r#"{{ "fixture": "core:fluorescent_panel_01", "x": {x}, "z": {z}, "intensity": {intensity}, "color": [1.0, 0.0, 0.0] }}"#
                ),
                2 => format!(
                    r#"{{ "fixture": "core:fluorescent_panel_01", "x": {x}, "z": {z}, "intensity": {intensity}, "color": [0.0, 1.0, 0.0] }}"#
                ),
                _ => format!(
                    r#"{{ "fixture": "core:fluorescent_panel_01", "x": {x}, "z": {z}, "intensity": {intensity}, "color": [0.1, 0.2, 0.9] }}"#
                ),
            };
            lights.push(entry);
        }
        let prop_count = usize::try_from(rng.int(0, 12)).unwrap_or(0);
        let mut props = Vec::new();
        for _ in 0..prop_count {
            let model = models[(rng.next_u32() as usize) % models.len()];
            let x = rng.range(-12.0, 30.0);
            let y = rng.range(-0.3, 2.5);
            let z = rng.range(-12.0, 30.0);
            let rotation = rng.range(0.0, 360.0);
            props.push(format!(
                r#"{{ "model": "{model}", "x": {x}, "y": {y}, "z": {z}, "rotation_degrees": {rotation} }}"#
            ));
        }
        let wall_count = usize::try_from(rng.int(0, 6)).unwrap_or(0);
        let mut walls = Vec::new();
        for _ in 0..wall_count {
            let x = rng.range(-12.0, 28.0);
            let z = rng.range(-12.0, 28.0);
            let w = rng.range(1.0, 20.0);
            let d = rng.range(0.3, 0.6);
            let openings = if rng.unit() < 0.5 {
                format!(
                    r#"[{{ "kind": "door", "offset": 0.5, "width": {}, "height": 2.1, "sill": 0.0 }}]"#,
                    rng.range(0.8, (w - 1.0).max(0.9))
                )
            } else {
                "[]".to_string()
            };
            walls.push(format!(
                r#"{{ "x": {x}, "z": {z}, "width": {w}, "depth": {d}, "height": 3.0, "openings": {openings} }}"#
            ));
        }

        let json = format!(
            r#"{{
                "format_version": 1,
                "id": "fuzz_{case}",
                "name": "Fuzz {case}",
                "spawn": {{ "x": 0.0, "z": 0.0 }},
                "rooms": [{}],
                "walls": [{}],
                "ceiling_lights": [{}],
                "props": [{}]
            }}"#,
            rooms.join(","),
            walls.join(","),
            lights.join(","),
            props.join(",")
        );
        let level = parse(&json);
        // Validation may reject the odd random level (enormous total area);
        // anything it accepts must bake and build safely.
        if crate::loader::validate_level(&level).is_err() {
            continue;
        }
        let lighting = LevelLighting::bake(&level);
        for info in lighting.rooms() {
            assert!(info.baseline.luminance().is_finite());
            assert!(
                (crate::lighting::AMBIENT_LEVEL..=crate::lighting::MAX_BRIGHTNESS)
                    .contains(&info.baseline.luminance())
            );
        }
        let (mesh, batches) = build_level_geometry_with_assets(&level, &catalog, &mut assets);
        assert_vertex_colors_safe(&mesh.all_vertices());
        for batch in &batches {
            assert_vertex_colors_safe(&batch.vertices);
        }
        assert!(mesh.vertex_count as u64 <= level.estimate_geometry().total_vertices);
        assert!(
            mesh.vertex_count as u64 + batches.iter().map(|b| b.vertices.len() as u64).sum::<u64>()
                <= MAX_LEVEL_VERTICES + MAX_LEVEL_PROP_VERTICES as u64
        );

        // A handful of representative sample points per level.
        for _ in 0..12 {
            let x = rng.range(-15.0, 35.0);
            let y = rng.range(-1.0, 6.0);
            let z = rng.range(-15.0, 35.0);
            let value = lighting.sample(x, y, z);
            assert!(value.is_finite(), "case {case}: sample ({x}, {y}, {z})");
            assert!(value.is_valid(), "case {case}: sample ({x}, {y}, {z})");
            assert!(
                (crate::lighting::AMBIENT_LEVEL..=crate::lighting::MAX_BRIGHTNESS)
                    .contains(&value.luminance())
            );
        }
    }
}

