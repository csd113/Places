struct Row {
    name: &'static str,
    level: LevelDef,
    stats: BuildStats,
    rooms: usize,
    lights: usize,
    openings: usize,
    props: usize,
}

fn openings_of(level: &LevelDef) -> usize {
    level.walls.iter().map(|wall| wall.openings.len()).sum()
}

#[test]
fn lighting_benchmark_report() {
    let catalog = shipped_catalog();
    let mut assets = shipped_assets();
    let repeat = if cfg!(debug_assertions) { 1 } else { 3 };

    let mut rows: Vec<Row> = Vec::new();
    let mut add = |name: &'static str, level: LevelDef, assets: &mut crate::props::PropAssets| {
        let (stats, mesh, batches) = measure(&level, &catalog, assets, repeat);
        assert_vertex_colors_safe(&mesh.all_vertices());
        for batch in &batches {
            assert_vertex_colors_safe(&batch.vertices);
        }
        assert!(
            stats.static_vertices <= usize::try_from(MAX_LEVEL_VERTICES).unwrap_or(usize::MAX),
            "{name}: static geometry exceeds the level budget"
        );
        rows.push(Row {
            name,
            stats,
            rooms: level.room_iter().count(),
            lights: level.ceiling_lights.len(),
            openings: openings_of(&level),
            props: level.props.len(),
            level,
        });
    };

    add("A Tiny", bench_tiny(), &mut assets);
    add("B Asset Demo", demo_level(), &mut assets);
    add("C Level 1", shipped_level("level1"), &mut assets);
    add("D 100 lights", bench_many_lights(100), &mut assets);
    add("E Large surfaces", bench_large_surfaces(), &mut assets);
    add("F 36 rooms", bench_many_rooms(6), &mut assets);
    add("G Prop heavy", bench_prop_heavy(), &mut assets);
    add("H Worst reasonable", bench_worst_reasonable(), &mut assets);
    // The three authored residential levels ship with the game, so their
    // geometry, prop and lighting cost is measured on every test run.
    add(
        "I The Residence",
        shipped_level("the_residence"),
        &mut assets,
    );
    add(
        "J Quiet Apartments",
        shipped_level("quiet_apartments"),
        &mut assets,
    );
    add(
        "K After the Leak",
        shipped_level("after_the_leak"),
        &mut assets,
    );

    println!();
    println!(
        "{:<20} {:>5} {:>6} {:>7} {:>8} {:>9} {:>8} {:>7} {:>8} {:>10} {:>10} {:>10} {:>9}",
        "level",
        "rooms",
        "lights",
        "opens",
        "props",
        "static V",
        "prop V",
        "draws",
        "models",
        "build ms",
        "cold ms",
        "bake ms",
        "est V"
    );
    for row in &rows {
        let stats = row.stats;
        println!(
            "{:<20} {:>5} {:>6} {:>7} {:>8} {:>9} {:>8} {:>7} {:>8} {:>10.2} {:>10.2} {:>10.2} {:>9}",
            row.name,
            row.rooms,
            row.lights,
            row.openings,
            row.props,
            stats.static_vertices,
            stats.prop_vertices,
            stats.prop_draws,
            stats.prop_models,
            stats.build_millis,
            stats.cold_millis,
            stats.bake_millis,
            stats.estimate_vertices
        );
    }
    println!();
    println!(
        "{:<20} {:>10} {:>10} {:>10} {:>10} {:>10} {:>10}",
        "level", "floor V", "ceiling V", "wall V", "light V", "static KiB", "prop KiB"
    );
    for row in &rows {
        let stats = row.stats;
        println!(
            "{:<20} {:>10} {:>10} {:>10} {:>10} {:>10} {:>10}",
            row.name,
            stats.floor_vertices,
            stats.ceiling_vertices,
            stats.wall_vertices,
            stats.light_vertices,
            stats.static_vbo_bytes() / 1024,
            stats.prop_vbo_bytes() / 1024
        );
    }
    println!();

    // Budget arithmetic must actually bound the geometry that is generated.
    for row in &rows {
        let estimate = row.level.estimate_geometry();
        assert!(
            row.stats.static_vertices as u64 <= estimate.total_vertices,
            "{}: estimate {} does not bound the built {} static vertices",
            row.name,
            estimate.total_vertices,
            row.stats.static_vertices
        );
    }

    // The prop expansion stays inside the documented prop budget.
    let demo_stats = rows
        .iter()
        .find(|row| row.name == "B Asset Demo")
        .expect("demo row")
        .stats;
    assert!(demo_stats.prop_vertices <= MAX_LEVEL_PROP_VERTICES);

    // A dense synthetic prop level batches per (model, spatial cell) so the
    // frustum can reject whole cells. Five models spread over a level this size
    // must still collapse into a coarse, PocketCHIP-friendly draw budget rather
    // than one draw per instance.
    let prop_row = rows
        .iter()
        .find(|row| row.name == "G Prop heavy")
        .expect("prop-heavy row")
        .stats;
    assert!(
        prop_row.prop_draws <= 5 * 16,
        "150 props across five models must stay inside 16 cells per model, got {}",
        prop_row.prop_draws
    );
    assert!(
        prop_row.prop_draws >= 5,
        "every model needs at least one draw, got {}",
        prop_row.prop_draws
    );
}

