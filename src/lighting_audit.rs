/// Extracts the four corners and colours of every quad in a vertex slice.
///
/// `add_quad` emits `p0, p1, p2, p0, p2, p3`, so the quad corners are indices
/// 0, 1, 2 and 5.
#[allow(clippy::type_complexity, clippy::chunks_exact_to_as_chunks)]
fn quads(vertices: &[crate::render::Vertex]) -> Vec<([(f32, f32); 4], [[f32; 4]; 4])> {
    assert_eq!(vertices.len() % 6, 0, "batches must be whole quads");
    vertices
        .chunks_exact(6)
        .map(|quad| {
            let corner = |index: usize| (quad[index].pos[0], quad[index].pos[2]);
            let color = |index: usize| quad[index].color;
            (
                [corner(0), corner(1), corner(2), corner(5)],
                [color(0), color(1), color(2), color(5)],
            )
        })
        .collect()
}

#[test]
fn merged_floor_and_ceiling_quads_keep_exact_samples_and_tile_the_room() {
    for level in [shipped_level("level1"), demo_level()] {
        let lighting = LevelLighting::bake(&level);
        let mesh = build_level_geometry(&level);
        let floor = mesh.triangles_for_family(SurfaceFamily::Floor);
        let ceiling = mesh.triangles_for_family(SurfaceFamily::Ceiling);
        assert_vertex_colors_safe(&floor);
        assert_vertex_colors_safe(&ceiling);

        // Every surviving corner keeps the exact sample it was given: find a
        // room that contains the corner and matches the baked colour.
        let matches_floor = |x: f32, z: f32, color: [f32; 4]| {
            (0..lighting.rooms().len()).any(|room| {
                let expected = lighting.sample_in_room(room, x, 0.0, z).to_array();
                (0..3).all(|channel| (color[channel] - expected[channel]).abs() < 1e-6)
            })
        };
        let matches_ceiling = |x: f32, z: f32, color: [f32; 4]| {
            lighting.rooms().iter().enumerate().any(|(room, info)| {
                let expected = lighting
                    .sample_in_room(room, x, info.height_m, z)
                    .to_array();
                let expected = [0.72 * expected[0], 0.72 * expected[1], 0.70 * expected[2]];
                (0..3).all(|channel| (color[channel] - expected[channel]).abs() < 1e-6)
            })
        };
        for quad in quads(&floor) {
            for index in 0..4 {
                let (x, z) = quad.0[index];
                assert!(
                    matches_floor(x, z, quad.1[index]),
                    "floor corner ({x}, {z}) colour {:?} does not match any room bake",
                    quad.1[index]
                );
            }
        }
        for quad in quads(&ceiling) {
            for index in 0..4 {
                let (x, z) = quad.0[index];
                assert!(
                    matches_ceiling(x, z, quad.1[index]),
                    "ceiling corner ({x}, {z}) colour {:?} does not match any room bake",
                    quad.1[index]
                );
            }
        }

        // Coverage: the emitted floor quads tile each room exactly, so no hole
        // or overlap was introduced by merging.
        for room in level.room_iter() {
            let x0 = room.x.min(room.x + room.width);
            let x1 = room.x.max(room.x + room.width);
            let area = (x1 - x0) * room.depth;
            let mut covered = 0.0_f64;
            for (corners, _) in quads(&floor) {
                // Shoelace area of the quad (axis-aligned rectangles here).
                let mut twice = 0.0_f64;
                for index in 0..4 {
                    let (ax, az) = corners[index];
                    let (bx, bz) = corners[(index + 1) % 4];
                    twice += f64::from(bx).mul_add(-f64::from(az), f64::from(ax) * f64::from(bz));
                }
                let center_x = corners.iter().map(|c| c.0).sum::<f32>() / 4.0;
                let center_z = corners.iter().map(|c| c.1).sum::<f32>() / 4.0;
                if center_x > x0
                    && center_x < x1
                    && center_z > room.z
                    && center_z < room.z + room.depth
                {
                    covered = twice.abs().mul_add(0.5, covered);
                }
            }
            assert!(
                (covered - f64::from(area)).abs() < f64::from(area).mul_add(0.01, 1e-3),
                "room floor coverage {covered} vs area {area}"
            );
        }
    }
}

#[test]
fn merged_wall_strips_share_exact_edges() {
    // A long lit corridor wall: consecutive wall quads on the same face must
    // meet with identical colours at their shared boundary (the cached corner
    // sample), so merging cannot introduce a seam.
    let wall_lights = format!("{},{}", light(4.0, 4.0, None), light(20.0, 4.0, None));
    let level = parse(&format!(
        r#"{{
            "format_version": 1,
            "id": "wall_edges",
            "name": "Wall Edges",
            "spawn": {{ "x": 0.0, "z": 0.0 }},
            "rooms": [{}],
            "walls": [{{ "x": -0.4, "z": -0.2, "width": 0.4, "depth": 24.0, "height": 3.0 }}],
            "ceiling_lights": [{wall_lights}]
        }}"#,
        room(-0.4, -0.2, 24.4, 8.0, 3.0),
    ));
    let mesh = build_level_geometry(&level);
    let wall = mesh.triangles_for(SurfaceKind::Wall);

    // Group vertices by the world coordinate across the wall's thickness
    // (x = -0.4 is one face, x = 0.0 the other) and by height; within a face,
    // the colour as a function of position must be single-valued. The wall's
    // end caps (z at the wall ends) deliberately use a different face tint, so
    // they are excluded.
    let mut samples: std::collections::HashMap<(i32, i32, i32), [f32; 4]> =
        std::collections::HashMap::new();
    for vertex in wall {
        if (vertex.pos[2] + 0.2).abs() < 1e-4 || (vertex.pos[2] - 23.8).abs() < 1e-4 {
            continue;
        }
        let key = (
            (vertex.pos[0] * 1000.0).round() as i32,
            (vertex.pos[1] * 1000.0).round() as i32,
            (vertex.pos[2] * 1000.0).round() as i32,
        );
        match samples.get(&key) {
            Some(existing) => assert_eq!(
                existing.map(f32::to_bits),
                vertex.color.map(f32::to_bits),
                "same wall position {key:?} carries two different colours"
            ),
            None => {
                samples.insert(key, vertex.color);
            }
        }
    }
    assert!(samples.len() > 8, "the wall must emit real geometry");
}
