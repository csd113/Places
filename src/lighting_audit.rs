/// Level F: many small rooms in a grid, each with two fixtures, joined by
/// doorways in their shared walls.
fn bench_many_rooms(grid: usize) -> LevelDef {
    let room_size = 8.0;
    let mut rooms = Vec::new();
    let mut lights = Vec::new();
    let mut walls = Vec::new();
    for row in 0..grid {
        for col in 0..grid {
            let x = col as f32 * room_size;
            let z = row as f32 * room_size;
            rooms.push(room(x, z, room_size, room_size, 3.0));
            lights.push(light(x + 2.5, z + 2.5, None));
            lights.push(light(x + 5.5, z + 5.5, None));
            // A doorway in the east wall of each room (interior walls only).
            if col + 1 < grid {
                walls.push(format!(
                    r#"{{ "x": {}, "z": {}, "width": 0.4, "depth": {}, "height": 3.0, "openings": [{{ "kind": "door", "offset": 3.0, "width": 1.2, "height": 2.1, "sill": 0.0 }}] }}"#,
                    x + room_size,
                    z,
                    room_size
                ));
            }
            if row + 1 < grid {
                walls.push(format!(
                    r#"{{ "x": {}, "z": {}, "width": {}, "depth": 0.4, "height": 3.0, "openings": [{{ "kind": "door", "offset": 3.0, "width": 1.2, "height": 2.1, "sill": 0.0 }}] }}"#,
                    x,
                    z + room_size,
                    room_size
                ));
            }
        }
    }
    parse(&format!(
        r#"{{
            "format_version": 1,
            "id": "bench_many_rooms",
            "name": "Bench Many Rooms",
            "spawn": {{ "x": 0.0, "z": 0.0 }},
            "rooms": [{}],
            "walls": [{}],
            "ceiling_lights": [{}]
        }}"#,
        rooms.join(","),
        walls.join(","),
        lights.join(",")
    ))
}

