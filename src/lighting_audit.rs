/// Minimal valid level JSON around a list of room definitions and light
/// entries, so each test can vary exactly one thing.
pub fn level_json(rooms_json: &str, lights_json: &str) -> String {
    format!(
        r#"{{
            "format_version": 1,
            "id": "audit",
            "name": "Audit",
            "spawn": {{ "x": 0.0, "z": 0.0 }},
            "rooms": [{rooms_json}],
            "ceiling_lights": [{lights_json}]
        }}"#
    )
}

/// Parses level JSON, panicking with the parser error if the test's own JSON is
/// wrong (every string here is generated by the tests, not shipped data).
pub fn parse(json: &str) -> LevelDef {
    LevelDef::from_json(json).unwrap_or_else(|error| panic!("test level must parse: {error}"))
}

/// Shorthand for one ceiling light.
pub fn light(x: f32, z: f32, intensity: Option<f32>) -> String {
    intensity.map_or_else(
        || format!(r#"{{ "fixture": "core:fluorescent_panel_01", "x": {x}, "z": {z} }}"#),
        |value| {
            format!(
                r#"{{ "fixture": "core:fluorescent_panel_01", "x": {x}, "z": {z}, "intensity": {value} }}"#
            )
        },
    )
}

/// One room definition.
pub fn room(x: f32, z: f32, width: f32, depth: f32, height: f32) -> String {
    format!(r#"{{ "x": {x}, "z": {z}, "width": {width}, "depth": {depth}, "height": {height} }}"#)
}

/// A square room with `count` fixtures spread evenly over it.
pub fn square_room_level(size: f32, height: f32, count: usize, intensity: Option<f32>) -> LevelDef {
    let mut lights = Vec::with_capacity(count);
    let (cols, rows) = fixture_grid(count);
    for row in 0..rows {
        for col in 0..cols {
            if row * cols + col >= count {
                break;
            }
            let x = size * (col as f32 + 1.0) / (cols as f32 + 1.0);
            let z = size * (row as f32 + 1.0) / (rows as f32 + 1.0);
            lights.push(light(x, z, intensity));
        }
    }
    parse(&level_json(
        &room(0.0, 0.0, size, size, height),
        &lights.join(","),
    ))
}

/// Grid shape for `count` roughly evenly spaced fixtures.
fn fixture_grid(count: usize) -> (usize, usize) {
    if count == 0 {
        return (0, 0);
    }
    let cols = (count as f32).sqrt().ceil() as usize;
    ((cols.max(1)), (count.div_ceil(cols.max(1))).max(1))
}

