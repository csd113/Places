#[test]
fn regression_raised_walls_do_not_blend_through_their_openings() {
    let sample_at = |level: &LevelDef, x: f32, y: f32, z: f32| {
        LevelLighting::bake(level).sample_in_room_luminance(1, x, y, z)
    };
    let solid_control = |mut level: LevelDef| {
        level.walls[0].openings.clear();
        level
    };

    // A walk-through doorway at floor level blends...
    let floor_wall = LevelLighting::bake(&shared_wall_level(0.0, 0.0, 1.0));
    assert!(
        floor_wall.rooms()[1].baseline.luminance() < floor_wall.rooms()[0].baseline.luminance()
    );
    let blended = sample_at(&shared_wall_level(0.0, 0.0, 1.0), 10.5, 0.0, 5.0);
    let floor_solid = sample_at(
        &solid_control(shared_wall_level(0.0, 0.0, 1.0)),
        10.5,
        0.0,
        5.0,
    );
    assert!(
        blended > floor_solid + 0.01,
        "a floor-level doorway must blend: {blended} vs solid {floor_solid}"
    );

    // ...but the same opening in a wall raised to 2.5 m is a hole near the
    // ceiling, not a passage: no light may leak through it.
    let raised = sample_at(&shared_wall_level(2.5, 0.0, 1.0), 10.5, 0.0, 5.0);
    let raised_solid = sample_at(
        &solid_control(shared_wall_level(2.5, 0.0, 1.0)),
        10.5,
        0.0,
        5.0,
    );
    assert!(
        (raised - raised_solid).abs() < 1e-5,
        "a raised wall's opening must not blend: {raised} vs solid {raised_solid}"
    );
    // Even at the opening's own height nothing leaks.
    let at_opening_height = sample_at(&shared_wall_level(2.5, 0.0, 1.0), 10.5, 2.7, 5.0);
    let height_solid = sample_at(
        &solid_control(shared_wall_level(2.5, 0.0, 1.0)),
        10.5,
        2.7,
        5.0,
    );
    assert!((at_opening_height - height_solid).abs() < 1e-5);

    // A sill above the floor on a grounded wall is a window, not a door.
    let window = sample_at(&shared_wall_level(0.0, 0.5, 1.0), 10.5, 0.0, 5.0);
    let window_solid = sample_at(
        &solid_control(shared_wall_level(0.0, 0.5, 1.0)),
        10.5,
        0.0,
        5.0,
    );
    assert!((window - window_solid).abs() < 1e-5);
}

#[test]
fn regression_invalid_openings_do_not_create_phantom_doorways() {
    let solid = LevelLighting::bake(&shared_wall_level(0.0, 0.0, 1.0));
    // Programmatic malformations that validation would normally reject: none
    // may blend, so the bake must match a wall with no opening at all.
    let reference = {
        let mut level = shared_wall_level(0.0, 0.0, 1.0);
        level.walls[0].openings.clear();
        LevelLighting::bake(&level)
    };
    let reference_sample = reference.sample_in_room_luminance(1, 10.5, 0.0, 5.0);
    for (label, mutate) in [
        (
            "zero width",
            (|o: &mut crate::level::WallOpeningDef| o.width = 0.0)
                as fn(&mut crate::level::WallOpeningDef),
        ),
        ("negative width", |o| o.width = -1.0),
        ("zero height", |o| o.height = 0.0),
        ("NaN height", |o| o.height = f32::NAN),
        ("infinite height", |o| o.height = f32::INFINITY),
        ("NaN sill", |o| o.sill = f32::NAN),
        ("non-finite offset", |o| o.offset = f32::INFINITY),
    ] {
        let mut level = shared_wall_level(0.0, 0.0, 1.0);
        mutate(&mut level.walls[0].openings[0]);
        let lighting = LevelLighting::bake(&level);
        assert_eq!(
            lighting.rooms(),
            reference.rooms(),
            "{label}: open malformed opening changed the bake"
        );
        let value = lighting.sample_in_room_luminance(1, 10.5, 0.0, 5.0);
        assert!(
            (value - reference_sample).abs() < 1e-5,
            "{label}: phantom doorway leaked light ({value} vs {reference_sample})"
        );
    }
    // The malformed wall still builds without panicking.
    let mut level = shared_wall_level(0.0, 0.0, 1.0);
    level.walls[0].openings[0].width = f32::NAN;
    assert_vertex_colors_safe(&build_level_geometry(&level).all_vertices());
    let _ = solid;
}

