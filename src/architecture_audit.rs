/// Walks one JSON node, recording the path of every sentinel string.
fn walk_sentinels(value: &serde_json::Value, path: &str, out: &mut Vec<String>) {
    match value {
        serde_json::Value::String(text) if text.starts_with("sentinel:") => {
            out.push(path.to_string());
        }
        serde_json::Value::Array(items) => {
            for (index, item) in items.iter().enumerate() {
                walk_sentinels(item, &format!("{path}[{index}]"), out);
            }
        }
        serde_json::Value::Object(map) => {
            for (key, item) in map {
                walk_sentinels(item, &format!("{path}.{key}"), out);
            }
        }
        serde_json::Value::Null
        | serde_json::Value::Bool(_)
        | serde_json::Value::Number(_)
        | serde_json::Value::String(_) => {}
    }
}

/// Every `key` whose value tree contains the sentinel, for the scan report.
