/// One triangle of an emitted batch, reduced to world and UV area.
struct EmittedTriangle {
    world_area: f32,
    uv_area: f32,
    material: MaterialIndex,
    points: [[f32; 3]; 3],
}

/// Every triangle of a mesh with its world area and UV area measured.
fn emitted_triangles(mesh: &crate::render::LevelMesh) -> Vec<EmittedTriangle> {
    let mut out = Vec::new();
    for range in &mesh.ranges {
        for chunk in range.indices.chunks(3) {
            let mut points = [[0.0f32; 3]; 3];
            let mut uv = [[0.0f32; 2]; 3];
            let mut complete = true;
            for (slot, index) in chunk.iter().enumerate() {
                let Some(vertex) = range.vertices.get(usize::from(*index)) else {
                    complete = false;
                    break;
                };
                points[slot] = vertex.pos;
                uv[slot] = vertex.uv;
            }
            if !complete {
                continue;
            }
            out.push(EmittedTriangle {
                world_area: triangle_area(points),
                uv_area: uv_triangle_area(uv),
                material: range.key.material,
                points,
            });
        }
    }
    out
}

fn triangle_area(points: [[f32; 3]; 3]) -> f32 {
    let a = [
        points[1][0] - points[0][0],
        points[1][1] - points[0][1],
        points[1][2] - points[0][2],
    ];
    let b = [
        points[2][0] - points[0][0],
        points[2][1] - points[0][1],
        points[2][2] - points[0][2],
    ];
    let cross = [
        a[1] * b[2] - a[2] * b[1],
        a[2] * b[0] - a[0] * b[2],
        a[0] * b[1] - a[1] * b[0],
    ];
    (cross[0] * cross[0] + cross[1] * cross[1] + cross[2] * cross[2]).sqrt() * 0.5
}

fn uv_triangle_area(uv: [[f32; 2]; 3]) -> f32 {
    let a = [uv[1][0] - uv[0][0], uv[1][1] - uv[0][1]];
    let b = [uv[2][0] - uv[0][0], uv[2][1] - uv[0][1]];
    (a[0] * b[1] - a[1] * b[0]).abs() * 0.5
}

