/// Probes the shared floor grid at and around every boundary: the height must
/// be the containing cell's everywhere a point is inside it, including next to
/// every edge and corner.
#[test]
fn test_room_floor_grid_is_continuous_around_cell_boundaries() {
    let level = parse(
        r#"{
            "format_version": 1,
            "id": "grid_probe",
            "name": "Grid Probe",
            "spawn": { "x": 1.0, "z": 1.0 },
            "room": { "x": 0.0, "z": 0.0, "width": 8.0, "depth": 6.0, "height": 3.0 },
            "floor_regions": [
                { "x": 2.0, "z": 1.0, "width": 2.0, "depth": 2.0, "offset_y": 0.75 },
                { "x": 4.5, "z": 3.0, "width": 2.0, "depth": 2.0, "offset_y": -0.5 }
            ]
        }"#,
    );
    let surfaces = LevelSurfaces::new(&level);
    let room = level.room_iter().next().expect("one room");
    let grid = surfaces.floor_grid(room);
    let eps = 1.0e-5_f32;
    for ix in 0..grid.cells_x() {
        let (Some(&x0), Some(&x1)) = (grid.xs.get(ix), grid.xs.get(ix + 1)) else {
            continue;
        };
        for iz in 0..grid.cells_z() {
            let (Some(&z0), Some(&z1)) = (grid.zs.get(iz), grid.zs.get(iz + 1)) else {
                continue;
            };
            let expected = grid.y_at(room, ix, iz);
            let mid = (f32::midpoint(x0, x1), f32::midpoint(z0, z1));
            assert!(
                (grid.height_at(room, mid.0, mid.1) - expected).abs() < 1e-6,
                "cell centre ({}, {}) disagrees",
                mid.0,
                mid.1
            );
            for (px, pz) in [
                (mid.0.min(x0 + eps), mid.1.min(z0 + eps)),
                (mid.0.max(x1 - eps), mid.1.min(z0 + eps)),
                (mid.0.min(x0 + eps), mid.1.max(z1 - eps)),
                (mid.0.max(x1 - eps), mid.1.max(z1 - eps)),
            ] {
                let got = grid.height_at(room, px, pz);
                assert!(
                    (got - expected).abs() < 1e-6,
                    "the point ({px}, {pz}) beside the edge of cell ({ix}, {iz}) \
                     resolves height {got}, not {expected}"
                );
            }
        }
    }
}

/// The walkable surface and the surface atlas must agree at every probe,
/// including exactly on region, ramp and stair boundaries and slightly either
/// side of them.
#[test]
fn test_walkable_floor_matches_surface_atlas_around_ramp_and_region_edges() {
    let level = parse(
        r#"{
            "format_version": 1,
            "id": "walk_probe",
            "name": "Walk Probe",
            "spawn": { "x": 1.0, "z": 1.0 },
            "room": { "x": 0.0, "z": 0.0, "width": 12.0, "depth": 12.0, "height": 4.0 },
            "floor_regions": [
                { "x": 6.0, "z": 2.0, "width": 3.0, "depth": 3.0, "offset_y": 1.0 }
            ],
            "ramps": [
                { "x": 1.0, "z": 2.0, "width": 1.0, "depth": 4.0, "rise": 1.0 }
            ],
            "stairs": [
                { "x": 3.0, "z": 6.0, "width": 1.2, "depth": 2.4, "rise": 0.8, "steps": 4 }
            ]
        }"#,
    );
    let surfaces = LevelSurfaces::new(&level);
    let floor = WalkableFloor::from_level(&level);
    let mut probes = Vec::new();
    let ramp = &level.ramps[0];
    let (rx0, rx1, rz0, rz1) = ramp.bounds();
    for z in [
        rz0,
        rz0 + 1e-5,
        rz0 - 1e-5,
        3.0,
        rz1 - 1e-5,
        rz1,
        rz1 + 1e-5,
    ] {
        for x in [rx0, f32::midpoint(rx0, rx1), rx1] {
            probes.push((x, z));
        }
    }
    let stair = &level.stairs[0];
    let (sx0, sx1, sz0, _sz1) = stair.bounds();
    for step in 0..=stair.step_count() {
        let boundary = sz0 + stair.tread_depth() * step as f32;
        for x in [sx0, f32::midpoint(sx0, sx1), sx1] {
            probes.push((x, boundary));
            probes.push((x, boundary - 1e-5));
            probes.push((x, boundary + 1e-5));
        }
    }
    let region = &level.floor_regions[0];
    let (gx0, gx1, gz0, gz1) = region.bounds();
    for (x, z) in [
        (gx0, 3.5),
        (gx1, 3.5),
        (f32::midpoint(gx0, gx1), gz0),
        (f32::midpoint(gx0, gx1), gz1),
        (gx0, gz0),
        (gx1, gz1),
        (gx1 - 1e-5, gz1 - 1e-5),
    ] {
        probes.push((x, z));
    }
    for (x, z) in probes {
        let atlas = surfaces.floor_y_at(x, z).expect("inside the room");
        let walk = floor
            .height_at(x, z)
            .unwrap_or_else(|| panic!("walkable floor has ({x}, {z})"));
        assert!(
            (atlas - walk).abs() < 1e-5,
            "at ({x}, {z}) the atlas says {atlas} and the walkable model says {walk}"
        );
    }
}

