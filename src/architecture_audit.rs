/// A sloping guardrail alongside a flight follows the flight's rise: its rail
/// top sits one rail-height above the stair surface at both ends, its posts
/// stay vertical, and its barrier box spans the slope.
#[test]
fn test_guardrail_follows_a_stair_flight_as_a_handrail() {
    let level = parse(
        r#"{
            "format_version": 1,
            "id": "handrail",
            "name": "Handrail",
            "spawn": { "x": 0.5, "z": 0.5 },
            "room": { "x": 0.0, "z": 0.0, "width": 10.0, "depth": 10.0, "height": 4.0 },
            "stairs": [
                { "x": 3.0, "z": 2.0, "width": 3.0, "depth": 2.0, "rise": 1.5, "steps": 5 }
            ],
            "guardrails": [
                { "x": 3.0, "z": 2.5, "length": 2.4, "rotation_degrees": 0.0,
                  "height": 0.95, "post_spacing": 0.8,
                  "material": "core:metal_brushed_01" }
            ]
        }"#,
    );
    let stair = &level.stairs[0];
    let rail = &level.guardrails[0];
    let surfaces = LevelSurfaces::new(&level);
    // The rail runs east along the stair's south side, from the foot to the
    // head, rising with the flight.
    // With no authored `y` or `rise`, the base line follows the walkable floor
    // from the foot (one riser up) to the head (the top tread), i.e. the
    // nosing line. The top rail therefore keeps a near-constant height above
    // the treads (within half a riser at mid-tread).
    assert!(
        (rail.base_y_at(&surfaces, 0.0) - 0.3).abs() < 1.0e-3,
        "the rail's foot sits on the first tread: {}",
        rail.base_y_at(&surfaces, 0.0)
    );
    assert!(
        (rail.base_y_at(&surfaces, 1.0) - 1.5).abs() < 1.0e-3,
        "the rail's head sits on the top tread: {}",
        rail.base_y_at(&surfaces, 1.0)
    );
    assert!((rail.resolved_rise(&surfaces) - 1.2).abs() < 1.0e-3);
    // The rail stays exactly one rail-height above the nosing line (the line
    // through the tread nosings), which is what a handrail is measured
    // against; above the flat tread surface it therefore runs between one
    // rail-height and one rail-height plus one riser.
    // The run spans the first nosing to the last (the top tread's front), so
    // the resolved base line is exactly the nosing line.
    for sample in 0..=40 {
        let fraction = sample as f32 / 40.0;
        let (x, z) = rail.point_at(fraction, 0.0);
        let nosing = 0.3 + 0.5 * (x - 3.0);
        let rail_top = rail.base_y_at(&surfaces, fraction) + rail.height();
        assert!(
            (rail_top - nosing - rail.height()).abs() < 1.0e-3,
            "at fraction {fraction} the rail is not tracking the nosing line"
        );
        let above_tread = rail_top - stair.offset_at(x, z);
        assert!(
            (rail.height() - 0.02..=rail.height() + stair.riser_height() + 0.02)
                .contains(&above_tread),
            "at fraction {fraction} the rail is {above_tread} m above the tread"
        );
    }
    let materials = logical_materials(&level);
    let mesh = build_level_geometry_with_materials(&level, &materials);
    // Posts are vertical: every quad's two bottom corners and two top corners
    // share the same plan position.
    let metal = materials.index_of("core:metal_brushed_01").expect("metal");
    let mut posts = 0;
    for triangle in emitted_triangles(&mesh) {
        if triangle.material != metal {
            continue;
        }
        let normal = triangle_normal(triangle.points);
        if normal[1].abs() > 0.99 {
            continue;
        }
        // A vertical post face spans y only at a constant plan edge.
        let ys: Vec<f32> = triangle.points.iter().map(|point| point[1]).collect();
        let min = ys.iter().copied().fold(f32::INFINITY, f32::min);
        let max = ys.iter().copied().fold(f32::NEG_INFINITY, f32::max);
        let two_levels = ys
            .iter()
            .filter(|value| (**value - min).abs() < 1.0e-4)
            .count()
            == 2
            || ys
                .iter()
                .filter(|value| (**value - max).abs() < 1.0e-4)
                .count()
                == 2;
        if two_levels && max - min > 0.2 && normal[1].abs() < 0.2 {
            posts += 1;
        }
    }
    assert!(posts > 0, "the rail emits vertical post faces");
    let solid = rail.solid_box(&surfaces).expect("the rail is solid");
    assert!(
        solid.max[1] >= stair.top_offset() + rail.height() - 0.05,
        "the barrier reaches the top rail: {solid:?}"
    );
}

