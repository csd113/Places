/// Builds a room with one ceiling light, a floor sample helper and the
/// architecture under test.
fn lighting_level(architecture: &str) -> LevelDef {
    let separator = if architecture.trim().is_empty() {
        ""
    } else {
        ","
    };
    parse(&format!(
        r#"{{
            "format_version": 1,
            "id": "lighting_arch",
            "name": "Lighting Arch",
            "spawn": {{ "x": 1.0, "z": 1.0 }},
            "room": {{ "x": 0.0, "z": 0.0, "width": 10.0, "depth": 8.0, "height": 3.0 }},
            "ceiling_lights": [
                {{ "fixture": "core:fluorescent_panel_01", "x": 3.0, "z": 2.0,
                   "brightness": 1.0 }}
            ]{separator}
            {architecture}
        }}"#
    ))
}

fn luminance(lighting: &LevelLighting, x: f32, z: f32) -> f32 {
    let color = lighting.sample_in_room(0, x, 0.0, z);
    color.r + color.g + color.b
}

/// A half wall between the fixture and a point darkens it; a guardrail on the
/// same line darkens it less, and neither turns the floor behind it black.
#[test]
fn test_half_walls_and_guardrails_occlude_without_black_bands() {
    let open = lighting_level("");
    let open_lighting = LevelLighting::bake(&open);
    // Just behind the barrier, still inside its shadow (a one-metre wall with
    // a ceiling fixture shadows the floor only ~0.8 m out).
    let behind_open = luminance(&open_lighting, 5.0, 2.0);

    let half = lighting_level(
        r#""half_walls": [ { "x": 4.6, "z": 0.5, "width": 0.2, "depth": 7.0,
                             "height": 1.0, "material": "core:wallpaper_yellow_01" } ]"#,
    );
    let half_lighting = LevelLighting::bake(&half);
    let behind_half = luminance(&half_lighting, 5.0, 2.0);
    assert!(
        behind_half < behind_open * 0.95,
        "a half wall between the light and the point blocks some light: \
         {behind_half} vs open {behind_open}"
    );
    assert!(
        behind_half > behind_open * 0.35,
        "a one-metre half wall does not black out the room: {behind_half} vs {behind_open}"
    );

    let rail = lighting_level(
        r#""guardrails": [ { "x": 4.6, "z": 0.5, "length": 7.0, "rotation_degrees": 90.0,
                             "height": 0.95, "material": "core:metal_brushed_01" } ]"#,
    );
    let rail_lighting = LevelLighting::bake(&rail);
    let behind_rail = luminance(&rail_lighting, 5.0, 2.0);
    assert!(
        behind_rail > behind_half,
        "a sparse rail shadows less than a solid half wall: {behind_rail} vs {behind_half}"
    );
    assert!(
        behind_rail > behind_open * 0.35,
        "the rail's barrier does not black out the room: {behind_rail} vs {behind_open}"
    );
}

/// An archway transmits light through its opening: the floor beyond the
/// opening is brighter than the floor beyond the solid pier.
#[test]
fn test_archway_openings_transmit_light() {
    // The fixture sits opposite the opening, so one straight ray crosses the
    // arch and another crosses the solid pier.
    let level = parse(
        r#"{
            "format_version": 1,
            "id": "arch_light",
            "name": "Arch Light",
            "spawn": { "x": 1.0, "z": 1.0 },
            "room": { "x": 0.0, "z": 0.0, "width": 10.0, "depth": 8.0, "height": 3.0 },
            "ceiling_lights": [
                { "fixture": "core:fluorescent_panel_01", "x": 3.0, "z": 5.0,
                   "brightness": 1.0 }
            ],
            "archways": [ { "x": 4.5, "z": 3.0, "width": 0.3, "depth": 4.0,
                           "height": 3.0, "opening_width": 1.2, "opening_height": 2.2,
                           "arch_rise": 0.2, "material": "core:wallpaper_yellow_01" } ]
        }"#,
    );
    let lighting = LevelLighting::bake(&level);
    // The opening is centred at z = 3 + 4/2 = 5.0 in the block's own run.
    let through_opening = luminance(&lighting, 6.0, 5.0);
    let behind_pier = luminance(&lighting, 6.0, 3.6);
    assert!(
        through_opening > behind_pier * 1.1,
        "the opening transmits light: opening {through_opening} vs pier {behind_pier}"
    );
}

