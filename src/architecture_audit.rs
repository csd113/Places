/// A point at run fraction `fraction` on the piece's length axis.
fn along_axis(bounds: (f32, f32, f32, f32), axis: WallAxis, fraction: f32) -> (f32, f32) {
    let (x0, x1, z0, z1) = bounds;
    match axis {
        WallAxis::X => (fraction.mul_add(x1 - x0, x0), f32::midpoint(z0, z1)),
        WallAxis::Z => (f32::midpoint(x0, x1), fraction.mul_add(z1 - z0, z0)),
    }
}

/// Ramp heights are monotone along the run and match the documented
/// `offset_y + rise * fraction` for every footprint orientation, positive or
/// negative rise, narrow or wide, on the floor or on a raised base.
#[test]
fn test_ramp_sweep_is_monotone_in_every_orientation() {
    let cases: [(f32, f32, f32, f32, f32, f32); 8] = [
        (1.0, 1.0, 1.0, 4.0, 0.0, 1.0),   // +Z run, positive
        (1.0, 1.0, 4.0, 1.0, 0.0, 1.0),   // +X run, positive
        (1.0, 6.0, 1.0, 4.0, 0.5, 1.0),   // +Z run on a plinth, positive
        (6.0, 6.0, 4.0, 1.0, 0.5, -1.0),  // +X run, negative
        (1.0, 1.0, 0.6, 4.0, 0.0, 2.0),   // narrow, maximum slope
        (1.0, 10.0, 4.0, 0.6, 0.0, 1.2),  // wide and shallow
        (10.0, 1.0, 1.0, 4.0, 2.5, 0.8),  // starting on a raised floor
        (14.0, 14.0, 4.0, 1.0, 0.0, 0.4), // minimum practical rise
    ];
    for (index, (x, z, width, depth, offset_y, rise)) in cases.into_iter().enumerate() {
        let level = ramp_level(&ramp(x, z, width, depth, offset_y, rise));
        let surfaces = LevelSurfaces::new(&level);
        let floor = WalkableFloor::from_level(&level);
        let piece = &level.ramps[0];
        let bounds = piece.bounds();
        let axis = piece.axis();
        let samples = 48;
        let mut previous = f32::NAN;
        for sample in 0..=samples {
            let fraction = sample as f32 / samples as f32;
            let (px, pz) = along_axis(bounds, axis, fraction);
            let atlas = surfaces.floor_y_at(px, pz).expect("inside the room");
            let walk = floor.height_at(px, pz).expect("inside the room");
            assert!(
                (atlas - walk).abs() < 1e-5,
                "case {index}: atlas {atlas} vs walkable {walk} at ({px}, {pz})"
            );
            let expected = offset_y + rise * fraction;
            assert!(
                (walk - expected).abs() < 1e-4,
                "case {index}: ramp height {walk} is not the documented {expected} at fraction {fraction}"
            );
            if previous.is_finite() {
                let monotone = if rise > 0.0 {
                    walk >= previous - 1e-5
                } else {
                    walk <= previous + 1e-5
                };
                assert!(
                    monotone,
                    "case {index}: ramp reverses at fraction {fraction}"
                );
            }
            previous = walk;
        }
        assert!(
            (previous - (offset_y + rise)).abs() < 1e-4,
            "case {index}: ramp ends at {previous}, not {}",
            offset_y + rise
        );
    }
}

/// Staircases at many parameter combinations keep their stepped surface exact:
/// the walkable model, the surface atlas and the documented tread heights agree
/// at every tread's start, middle and end.
#[test]
fn test_stair_sweep_steps_exactly_once_per_tread() {
    let cases: [(u32, f32, f32, f32, f32, f32); 6] = [
        // steps, rise, width, depth, offset_y, expected axis
        (2, 0.8, 0.4, 0.6, 0.0, 0.0),  // minimum steps, minimum-ish run
        (3, 0.3, 4.0, 3.0, 0.0, 0.0),  // small riser, long tread
        (20, 2.0, 1.2, 4.0, 0.0, 0.0), // many steps, maximum riser
        (4, 0.8, 1.0, 1.0, 1.5, 0.0),  // exactly square plan (ties resolve to X)
        (5, 0.75, 0.9, 2.0, -0.25, 0.0), // recessed foot
        (16, 2.4, 2.0, 4.8, 0.0, 0.0), // long flight
    ];
    for (index, (steps, rise, width, depth, offset_y, _)) in cases.into_iter().enumerate() {
        let level = stair_level(&stair(1.0, 1.0, width, depth, offset_y, rise, steps));
        let surfaces = LevelSurfaces::new(&level);
        let floor = WalkableFloor::from_level(&level);
        let piece = &level.stairs[0];
        let bounds = piece.bounds();
        let axis = piece.axis();
        assert_eq!(piece.step_count(), steps);
        for step in 0..steps {
            let (start, end) = piece.tread_span(step);
            let expected = offset_y + piece.riser_height() * (step + 1) as f32;
            for at in [start + 1e-4, f32::midpoint(start, end), end - 1e-4] {
                let (px, pz) = match axis {
                    WallAxis::X => (at, f32::midpoint(bounds.2, bounds.3)),
                    WallAxis::Z => (f32::midpoint(bounds.0, bounds.1), at),
                };
                let atlas = surfaces.floor_y_at(px, pz).expect("inside the room");
                let walk = floor.height_at(px, pz).expect("inside the room");
                assert!(
                    (atlas - walk).abs() < 1e-5,
                    "case {index} step {step}: atlas {atlas} vs walkable {walk} at {at}"
                );
                assert!(
                    (walk - expected).abs() < 1e-4,
                    "case {index} step {step}: walkable {walk} is not the documented {expected} at {at}"
                );
            }
        }
        let (head_x, head_z) = along_axis(bounds, axis, 1.0 - 1e-6);
        let head = floor.height_at(head_x, head_z).expect("inside the room");
        assert!(
            (head - (offset_y + rise)).abs() < 1e-4,
            "case {index}: the top tread is at {head}, not {}",
            offset_y + rise
        );
    }
}

