/// A column inside a raised floor region starts on the region's floor and
/// stops at its own room's ceiling, and a column whose top meets that ceiling
/// exactly emits no cap (so it never fights the ceiling plane).
#[test]
fn test_column_default_height_resolves_the_local_ceiling_and_region_floor() {
    let level = parse(
        r#"{
            "format_version": 1,
            "id": "column_ceiling",
            "name": "Column Ceiling",
            "spawn": { "x": 0.5, "z": 0.5 },
            "rooms": [
                { "x": 0.0, "z": 0.0, "width": 6.0, "depth": 6.0, "height": 2.6 },
                { "x": 6.0, "z": 0.0, "width": 4.0, "depth": 6.0, "height": 4.0 }
            ],
            "floor_regions": [
                { "x": 1.0, "z": 1.0, "width": 2.0, "depth": 2.0, "offset_y": 1.0 }
            ],
            "columns": [
                { "x": 1.5, "z": 1.5, "width": 0.3, "depth": 0.3 },
                { "x": 7.0, "z": 1.0, "width": 0.3, "depth": 0.3 },
                { "x": 3.0, "z": 3.0, "width": 0.3, "depth": 0.3, "height": 1.0 }
            ]
        }"#,
    );
    let materials = logical_materials(&level);
    let solids = level.architecture_solids();
    assert_eq!(solids.len(), 3);
    // The column on the raised region: base at the region floor, top at the
    // low room's ceiling.
    let raised = solids
        .iter()
        .find(|solid| (solid.min[0] - 1.5).abs() < 1e-4)
        .expect("the raised column is solid");
    assert!((raised.min[1] - 1.0).abs() < 1e-4, "{:?}", raised.min);
    assert!((raised.max[1] - 2.6).abs() < 1e-4, "{:?}", raised.max);
    // The column in the tall room reaches 4.0.
    let tall = solids
        .iter()
        .find(|solid| (solid.min[0] - 7.0).abs() < 1e-4)
        .expect("the tall column is solid");
    assert!((tall.max[1] - 4.0).abs() < 1e-4, "{:?}", tall.max);
    // An authored height wins over the ceiling, and its cap is drawn.
    let short = solids
        .iter()
        .find(|solid| (solid.min[0] - 3.0).abs() < 1e-4)
        .expect("the short column is solid");
    assert!((short.max[1] - 1.0).abs() < 1e-4, "{:?}", short.max);
    let mesh = build_level_geometry_with_materials(&level, &materials);
    // Count upward-facing triangles over each column footprint (the caps).
    let cap_area = |x: f32, z: f32| -> f32 {
        emitted_triangles(&mesh)
            .iter()
            .filter(|triangle| {
                let normal = triangle_normal(triangle.points);
                normal[1] > 0.99
                    && triangle
                        .points
                        .iter()
                        .all(|point| (point[0] - x).abs() < 0.35 && (point[2] - z).abs() < 0.35)
            })
            .map(|triangle| triangle.world_area)
            .sum()
    };
    assert!(
        cap_area(1.5, 1.5) < 1.0e-6,
        "a column flush with the ceiling draws no cap"
    );
    assert!(cap_area(7.0, 1.0) < 1.0e-6, "the tall column is flush too");
    assert!(
        (cap_area(3.0, 3.0) - 0.09).abs() < 1.0e-3,
        "an authored-height column draws its cap: {}",
        cap_area(3.0, 3.0)
    );
}

/// A half wall whose cap meets the ceiling exactly skips the cap; one that
