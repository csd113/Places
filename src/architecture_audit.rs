/// A guardrail run at every angle emits finite geometry with the correct
/// length, level rail tops and vertical posts, and collision that spans the
/// run.
#[test]
fn test_guardrails_work_at_every_orientation() {
    for angle in [0.0f32, 30.0, 45.0, 90.0, 135.0, 180.0, 270.0, 359.0] {
        let json = format!(
            r#"{{
                "format_version": 1,
                "id": "rail_angle",
                "name": "Rail Angle",
                "spawn": {{ "x": 0.5, "z": 0.5 }},
                "room": {{ "x": 0.0, "z": 0.0, "width": 12.0, "depth": 12.0, "height": 3.0 }},
                "guardrails": [
                    {{ "x": 3.0, "z": 3.0, "length": 4.0,
                       "rotation_degrees": {angle}, "height": 1.0 }}
                ]
            }}"#
        );
        let level = parse(&json);
        let rail = &level.guardrails[0];
        let materials = logical_materials(&level);
        let mesh = build_level_geometry_with_materials(&level, &materials);
        let mut triangles = 0;
        for triangle in emitted_triangles(&mesh) {
            assert!(
                triangle.world_area > 1.0e-9,
                "angle {angle}: zero-area face"
            );
            for point in triangle.points {
                assert!(
                    point.iter().all(|value| value.is_finite()),
                    "angle {angle}: non-finite point {point:?}"
                );
            }
            triangles += 1;
        }
        assert!(triangles > 0, "angle {angle}: the rail emits faces");
        // The run's endpoints and the top rail's height.
        let start = rail.point_at(0.0, 0.0);
        let end = rail.point_at(1.0, 0.0);
        let length = (end.0 - start.0).hypot(end.1 - start.1);
        assert!((length - 4.0).abs() < 1.0e-4, "angle {angle}: run {length}");
        let aabbs = level.architecture_solids();
        assert_eq!(aabbs.len(), 1, "angle {angle}: one barrier box");
        // The barrier spans the run: its diagonal is close to the run's length
        // plus the rail width.
        let barrier = aabbs[0];
        let dx = barrier.max[0] - barrier.min[0];
        let dz = barrier.max[2] - barrier.min[2];
        let diagonal = dx.hypot(dz);
        assert!(
            diagonal > 3.9 && diagonal < 4.2,
            "angle {angle}: barrier diagonal {diagonal}"
        );
        assert!((barrier.min[1] + 0.2).abs() < 0.3, "angle {angle}");
    }
}

/// Thresholds and baseboards are drawn at the documented angles with a real,
/// finite extent; their length along the run is exactly as authored.
#[test]
fn test_rotated_trim_keeps_its_length_and_plane() {
    for angle in [0.0f32, 30.0, 90.0, 135.0, 270.0] {
        let json = format!(
            r#"{{
                "format_version": 1,
                "id": "trim_angle",
                "name": "Trim Angle",
                "spawn": {{ "x": 0.5, "z": 0.5 }},
                "room": {{ "x": 0.0, "z": 0.0, "width": 12.0, "depth": 12.0, "height": 3.0 }},
                "thresholds": [
                    {{ "x": 6.0, "z": 6.0, "length": 1.0,
                       "rotation_degrees": {angle}, "material": "core:metal_brushed_01" }}
                ],
                "baseboards": [
                    {{ "x": 2.0, "z": 2.0, "length": 3.0,
                       "rotation_degrees": {angle}, "material": "core:plastic_panel_01" }}
                ]
            }}"#
        );
        let level = parse(&json);
        let materials = logical_materials(&level);
        let mesh = build_level_geometry_with_materials(&level, &materials);
        // The threshold's top face spans exactly `length` along its own axis
        // and its ends are `thickness` apart across it.
        let threshold = &level.thresholds[0];
        let materials_for = |id: &str| {
            materials
                .index_of(id)
                .unwrap_or_else(|| panic!("{id} resolves"))
        };
        let threshold_material = materials_for("core:metal_brushed_01");
        let baseboard_material = materials_for("core:plastic_panel_01");
        let board = &level.baseboards[0];
        let (ax, az) = board.across();
        let mut threshold_top = 0.0f32;
        let mut baseboard_front = 0.0f32;
        for triangle in emitted_triangles(&mesh) {
            let normal = triangle_normal(triangle.points);
            if triangle.material == threshold_material && normal[1] > 0.99 {
                threshold_top += triangle.world_area;
            }
            let across_facing = (normal[0] * ax + normal[2] * az).abs() > 0.99;
            if triangle.material == baseboard_material && across_facing {
                baseboard_front += triangle.world_area;
            }
        }
        assert!(
            (threshold_top - threshold.length * threshold.thickness()).abs() < 1.0e-3,
            "angle {angle}: threshold top covers {threshold_top}"
        );
        let expected_front = board.length * board.height();
        assert!(
            (baseboard_front - expected_front).abs() < 1.0e-3,
            "angle {angle}: baseboard front covers {baseboard_front}, expected {expected_front}"
        );
    }
}

fn triangle_normal(points: [[f32; 3]; 3]) -> [f32; 3] {
    let a = [
        points[1][0] - points[0][0],
        points[1][1] - points[0][1],
        points[1][2] - points[0][2],
    ];
    let b = [
        points[2][0] - points[0][0],
        points[2][1] - points[0][1],
        points[2][2] - points[0][2],
    ];
    let cross = [
        a[1] * b[2] - a[2] * b[1],
        a[2] * b[0] - a[0] * b[2],
        a[0] * b[1] - a[1] * b[0],
    ];
    let length = (cross[0] * cross[0] + cross[1] * cross[1] + cross[2] * cross[2]).sqrt();
    if length <= 1.0e-12 {
        return [0.0, 0.0, 0.0];
    }
    [cross[0] / length, cross[1] / length, cross[2] / length]
}

